#!/usr/bin/env node
// Prepares a harness test app for a handler variant: adds the package to its package.json and
// wraps its next.config so the variant's handlers are wired in.
//
//   node inject-handlers.mjs <appDir> branch <tarball>   this branch, packed; wired with withCache
//   node inject-handlers.mjs <appDir> pkg-16.4.2         the published 16.4.2 from npm; wired the
//                                                        16.4.2 way (cacheHandlers + a data
//                                                        handler file using createCacheHandler)
//
// The fixture's own config is kept as next.config.user.{cjs,mjs} and a generated next.config.mjs
// imports it, so .js (CJS or ESM), .mjs, .ts/.mts and "no config" all end up the same way.
// TypeScript configs are transpiled to CJS with the `typescript` from the app or the next.js
// checkout (NEXT_REPO_DIR).
import { existsSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const PACKAGE_NAME = "@mrjasonroy/cache-components-cache-handler";
const PUBLISHED_VERSION = "16.4.2";
// Next's own lookup order (packages/next/src/shared/lib/constants.ts CONFIG_FILES).
const CONFIG_FILES = ["next.config.js", "next.config.mjs", "next.config.ts", "next.config.mts"];

const [appDir, variant, tarball] = process.argv.slice(2);
if (!appDir || !["branch", "pkg-16.4.2"].includes(variant) || (variant === "branch" && !tarball)) {
  console.error("usage: inject-handlers.mjs <appDir> branch <tarball> | <appDir> pkg-16.4.2");
  process.exit(2);
}

const packageJsonPath = join(appDir, "package.json");
const pkg = JSON.parse(readFileSync(packageJsonPath, "utf8"));
pkg.dependencies = {
  ...pkg.dependencies,
  [PACKAGE_NAME]: variant === "branch" ? `file:${tarball}` : PUBLISHED_VERSION,
  ioredis: pkg.dependencies?.ioredis ?? "^5.4.1",
};
writeFileSync(packageJsonPath, `${JSON.stringify(pkg, null, 2)}\n`);

function loadTypeScript() {
  const roots = [join(appDir, "package.json")];
  if (process.env.NEXT_REPO_DIR) {
    roots.push(join(process.env.NEXT_REPO_DIR, "package.json"));
  }
  for (const root of roots) {
    try {
      return createRequire(root)("typescript");
    } catch {
      // try the next root
    }
  }
  throw new Error("typescript not found in the app or NEXT_REPO_DIR; cannot load next.config.ts");
}

const configFile = CONFIG_FILES.find((file) => existsSync(join(appDir, file)));
let userFile = null;

if (configFile) {
  const source = join(appDir, configFile);
  if (configFile.endsWith(".ts") || configFile.endsWith(".mts")) {
    const ts = loadTypeScript();
    const { outputText } = ts.transpileModule(readFileSync(source, "utf8"), {
      compilerOptions: {
        module: ts.ModuleKind.CommonJS,
        target: ts.ScriptTarget.ES2022,
        esModuleInterop: true,
      },
      fileName: configFile,
    });
    userFile = "next.config.user.cjs";
    writeFileSync(join(appDir, userFile), outputText);
    rmSync(source);
  } else {
    const isEsm = configFile.endsWith(".mjs") || pkg.type === "module";
    userFile = isEsm ? "next.config.user.mjs" : "next.config.user.cjs";
    renameSync(source, join(appDir, userFile));
  }
}

const userImport = userFile
  ? `import * as userModule from "./${userFile}";`
  : "const userModule = { default: {} };";

// How each variant turns the fixture's config (handler keys removed) into a cached one.
const variants = {
  branch: {
    imports: `import { withCache } from "${PACKAGE_NAME}";`,
    apply: `const options = JSON.parse(process.env.NEXT_DEPLOY_WITH_CACHE_OPTIONS || "{}");
function applyPackage(config) {
  return withCache(config, options);
}`,
  },
  // 16.4.2's documented setup (its README's quick start): one data-cache handler file for
  // "use cache" and "use cache: remote" in cacheHandlers, and cacheMaxMemorySize: 0. No page
  // handler. (16.4.2's createCacheConfig required an isrHandlerPath, so it is not used here.)
  "pkg-16.4.2": {
    imports: `import { fileURLToPath } from "node:url";`,
    apply: `function applyPackage(config) {
  const handler = fileURLToPath(new URL("./data-cache-handler.mjs", import.meta.url));
  return {
    ...config,
    cacheHandlers: { default: handler, remote: handler },
    cacheMaxMemorySize: 0,
  };
}`,
  },
};

if (variant === "pkg-16.4.2") {
  writeFileSync(
    join(appDir, "data-cache-handler.mjs"),
    `// Generated by tests/next-deploy/inject-handlers.mjs (16.4.2 wiring)
import { createCacheHandler } from "${PACKAGE_NAME}";

// CACHE_KEY_PREFIX is set per deployment by e2e-deploy.sh, so concurrent apps on one Redis
// keep their tags apart.
const prefix = process.env.CACHE_KEY_PREFIX ?? "nextjs:";

export default createCacheHandler({
  type: "redis",
  keyPrefix: \`\${prefix}cache:\`,
  tagPrefix: \`\${prefix}tags:\`,
});
`,
  );
}

// The fixture's own handlers win by default (NEXT_DEPLOY_FIXTURE_HANDLERS=keep): several
// suites assert on their instrumented handlers. The package fills every slot the fixture leaves
// empty. "replace" puts ours in default/remote/page and keeps only the fixture's extra kinds.
// Whatever happened is written to .handler-notes for the report. When a fixture handler stays in
// the config, .handler-instances says "1": that handler keeps its store in process memory, so
// e2e-deploy.sh runs a single instance instead of putting it behind the round-robin proxy.
const wrapper = `// Generated by tests/next-deploy/inject-handlers.mjs (variant: ${variant})
import { rmSync, writeFileSync } from "node:fs";
${variants[variant].imports}
${userImport}

${variants[variant].apply}

const policy = process.env.NEXT_DEPLOY_FIXTURE_HANDLERS === "replace" ? "replace" : "keep";

function unwrap(mod) {
  let value = mod.default ?? mod;
  while (value && typeof value === "object" && value.__esModule && "default" in value) {
    value = value.default;
  }
  return value;
}

function wrap(config = {}) {
  const { cacheHandler: fixturePage, cacheHandlers: fixtureHandlers, ...rest } = config;
  const wrapped = applyPackage(rest);
  const notes = [];
  let fixtureHandlerLive = false;

  if (policy === "keep") {
    fixtureHandlerLive = Boolean(fixturePage || fixtureHandlers);
    if (fixturePage) {
      wrapped.cacheHandler = fixturePage;
      notes.push("fixture cacheHandler kept");
    }
    if (fixtureHandlers) {
      wrapped.cacheHandlers = { ...wrapped.cacheHandlers, ...fixtureHandlers };
      for (const kind of Object.keys(fixtureHandlers)) {
        notes.push(\`fixture cacheHandlers.\${kind} kept\`);
      }
    }
  } else {
    if (fixturePage) notes.push("fixture cacheHandler replaced");
    if (fixtureHandlers) {
      const ours = wrapped.cacheHandlers ?? {};
      wrapped.cacheHandlers = { ...fixtureHandlers, ...ours };
      notes.push("fixture cacheHandlers merged under ours");
      fixtureHandlerLive = Object.keys(fixtureHandlers).some((kind) => !(kind in ours));
    }
  }

  writeFileSync(new URL("./.handler-notes", import.meta.url), notes.join("; "));
  const instancesFile = new URL("./.handler-instances", import.meta.url);
  if (fixtureHandlerLive) {
    writeFileSync(instancesFile, "1");
  } else {
    rmSync(instancesFile, { force: true });
  }
  return wrapped;
}

const user = unwrap(userModule);

export default typeof user === "function"
  ? async (phase, context) => wrap(await user(phase, context))
  : wrap(await user);
`;

writeFileSync(join(appDir, "next.config.mjs"), wrapper);
console.error(`[next-deploy] wrapped ${configFile ?? "(no config)"} for ${variant}`);
